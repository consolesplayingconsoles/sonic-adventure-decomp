void sound_play_bank(Uint8 bank, Uint8 number)
{
    int voice;
    if (bank == 15) {
        BGM_Play(number);
    } else if (bank >= 16) {
        bank -= 16;
        voice = ((bank & 0xf0) << 4) | number;
        Serif_Play(voice);
    } else {
        sound_slot_play(bank, number, 0, 37);
        sound_slot_set_volume(127, 37);
    }
}
