void ObjectECDoorBlock(struct task *task)
{
    struct task_work *work = task->work;

    if (CheckRangeOut(task)) {
        return;
    }
    switch (work->mode) {
    case BATTEN_INIT:
        BATTEN_KIND(work) = work->ang.z;
        work->ang.z = 0;
        CCL_Init(task, batten_shapes, COLLISION_OBJECT, 1, 1);
        task->destructor = BlockDestructor;
        task->draw = BlockDisplayer;
        work->mode = BATTEN_RUN;
        break;
    case BATTEN_RUN:
        if (ObjectECDoorBlock_sub(work) == TRUE) {
            work->flags |= BATTEN_SHOWN;
        } else {
            work->flags &= ~BATTEN_SHOWN;
        }
        break;
    }
    if (work->flags & BATTEN_SHOWN) {
        DisplayBlock(work);
    }
}

void BlockDisplayer(struct task *task)
{
    struct task_work *work = task->work;

    if (work->flags & BATTEN_SHOWN) {
        DisplayBlock(work);
    }
}

void BlockDestructor(struct task *task)
{
}

void DisplayBlock(struct task_work *work)
{
    Angle ang;

    SetObjectTexture();
    njPushMatrix(NULL);
    njTranslateV(NULL, &work->pos);
    TURN_VIA(njRotateY, work->ang.y, ang);
    late_DrawObject(&batten_object);
    late_DrawObjectClipEx(1);
}
