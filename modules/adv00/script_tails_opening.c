/* after event 48 in the station act, the section goes to Emerald Coast act 1.
 * the hotel's front, the station's front and the train open then. once Emerald
 * Coast is cleared, event 50 plays in the hotel act, and the section ends
 * whatever story_going_to returns */
void mainMilesSS01(int seq)
{
    switch (seq) {
    case 0:
        if (GetStageNumber() !=
            STAGE_ACT(STAGE_STATION_SQUARE, STATION_SQUARE_STATION)) {
            return;
        }
        SeqEvent(48);
        break;
    case 1:
        SeqChangeStage(STAGE_BEACH, 1);
        SeqSetFlag(FLAG_TAILS_SS_HOTEL_FRONT);
        SeqSetFlag(FLAG_TAILS_SS_STATION_FRONT);
        SeqSetFlag(FLAG_TAILS_TRAIN);
        SeqSetFlag(FLAG_TAILS_UNK_83);
        break;
    case 2:
        if (!SeqCheckClearAction(STAGE_BEACH)) {
            return;
        }
        if (!SeqCheckStage(STAGE_STATION_SQUARE, STATION_SQUARE_HOTEL)) {
            return;
        }
        SeqEvent(50);
        break;
    case 3:
        SeqCheckNextStage(STAGE_MYSTIC_RUINS, MYSTIC_RUINS_STATION);
        SeqEndSection();
        break;
    default:
        return;
    }
    SeqNext();
}
