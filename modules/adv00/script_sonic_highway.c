void script_sonic_highway_init(void)
{
    if (SeqCheckClearAction(STAGE_HIGHWAY)) {
        story_set_time(TIME_DAY);
    } else {
        story_set_time(TIME_NIGHT);
    }
}

/* once Speed Highway is cleared, event 21 plays in the casino act, and the
 * train and the station's front and back open again. the section ends as the
 * game goes to the Mystic Ruins */
void script_sonic_highway_step(int seq)
{
    switch (seq) {
    case 0:
        if (!SeqCheckClearAction(STAGE_HIGHWAY)) {
            return;
        }
        if (!SeqCheckStage(STAGE_STATION_SQUARE, STATION_SQUARE_CASINO)) {
            return;
        }
        SeqEvent(21);
        SeqSetFlag(FLAG_SONIC_TRAIN);
        SeqSetFlag(FLAG_SONIC_UNK_82);
        SeqSetFlag(FLAG_SONIC_SS_STATION_FRONT);
        SeqSetFlag(FLAG_SONIC_SS_STATION_BACK);
        break;
    case 1:
        if (!SeqCheckNextStage(STAGE_MYSTIC_RUINS, MYSTIC_RUINS_STATION)) {
            return;
        }
        SeqEndSection();
        break;
    default:
        return;
    }
    SeqNext();
}
