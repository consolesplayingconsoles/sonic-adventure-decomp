#define DEBUG_PAD 1 /* the second pad's index */

void race_debug_step(struct race_game *game)
{
    if (perG[DEBUG_PAD].press & PDD_DGT_TA) {
        if (cracker_on()) {
            cracker_stop();
        } else {
            cracker_start();
        }
    }
    if (perG[1].press & (1 << 17)) {
        FUN_0cb8d408(game, RACE_CAMERA_FINISH);
    }
}
