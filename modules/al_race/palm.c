/* the palm */
#define PALM(task) ((NJS_OBJECT **)(task)->motion)
extern NJS_OBJECT dat_0cbd0f40;

/* the palm's state, in its task's motion: its object */

void race_palm_start(struct task *task, void *arg);
void race_palm_draw(struct task *task);

static const struct task_desc race_palm_desc = {
    sizeof(NJS_OBJECT *), TASK_WORK,      race_palm_start,
    race_palm_draw,       race_palm_draw, NULL};
extern NJS_OBJECT *const race_palm_object;

void FUN_0cb96380(struct task *task)
{
    MirenInitTask(task, &race_palm_desc, (void *)&race_palm_object);
}

void race_palm_start(struct task *task, void *arg)
{
    NJS_OBJECT **object = PALM(task);

    *object = *(NJS_OBJECT **)arg;
}

void race_palm_draw(struct task *task)
{
    struct task_work *work;
    NJS_OBJECT **object;
    struct angles *ang;
    Angle turn;

    if (loop_count == 0) {
        if (!CheckRange(task)) {
            work = task->work;
            object = PALM(task);
            njPushMatrix(NULL);
            njTranslateV(NULL, &work->pos);
            ang = &work->ang;
            TURN_VIA(njRotateY, ang->y, turn);
            SetObjectTexture();
            late_DrawObject(*object);
            late_DrawObjectClipEx(1);
        }
    }
}
