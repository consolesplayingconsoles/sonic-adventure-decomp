/* a puff's frames, snabop01 to 08. a puff goes once its frame passes the
 * last */
#define SAND_FRAMES 8

/* a puff's vars: the params sand_step reads */
#define SAND(particle) ((struct sand_vars *)&(particle)->vars)
struct sand_vars {
    struct dust_params *params;
};

void sand_step(struct particle *particle, struct particle_pool *pool);
extern const NJS_TEXANIM sand_frames[8];
extern const struct particle_anim sand_anim;
extern struct particle_pool_spec sand_pool;
void sand_create_from(struct dust_params *params);
void sand_step(struct particle *particle, struct particle_pool *pool)
{
    struct dust_params *params;
    Float keep;
    int last = 8 - 1;
    NJS_VECTOR *speed;
    NJS_POINT3 *pos;
    particle->frame = particle->time;
    if (particle->frame > last) {
        particle->frame = last;
        SpFreeTask(particle);
        return;
    }
    params = ((struct sand_vars *)&(particle)->vars)->params;
    speed = &particle->speed;
    pos = &particle->pos;
    keep = 1.0F - params->drag;
    particle->time += params->rate;
    particle->scale += params->growth;
    speed->x *= keep;
    speed->y = (speed->y * keep) + params->lift;
    speed->z *= keep;
    pos->x += speed->x;
    pos->y += speed->y;
    pos->z += speed->z;
}
