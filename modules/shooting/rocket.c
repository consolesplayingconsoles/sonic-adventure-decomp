enum shooting_rocket_mode {
    ROCKET_INIT = 0,
    ROCKET_WAIT = 1,
    ROCKET_BLOW = 3,
    ROCKET_GONE = 4
};

extern NJS_TEXLIST texlist_shooting0;
extern NJS_OBJECT shooting_rocket_object;

void shooting_rocket_draw(struct task *task);
void shooting_rocket_destroy(struct task *task);
void shooting_rocket_take_touch(struct task *task);
extern struct collision_shape shooting_rocket_shapes[1];

void shooting_rocket_step(struct task *task)
{
    struct task_work *work = task->work;

    shooting_rocket_take_touch(task);
    switch (work->mode) {
    case ROCKET_INIT:
        work->mode = ROCKET_WAIT;
        work->vars.f[0] = 0.0F; /* nothing reads it */
        task->destructor = shooting_rocket_destroy;
        task->draw = shooting_rocket_draw;
        CCL_Init(task, shooting_rocket_shapes, COLLISION_OBJECT, 1, 1);
        break;
    case ROCKET_WAIT:
        EntryColliList(work);
        break;
    case ROCKET_BLOW:
        CreateBomb(&work->pos, 2.0F);
        work->mode = ROCKET_GONE;
        break;
    case ROCKET_GONE:
        DestroyTask(task);
        break;
    }
    shooting_rocket_draw(task);
}

void shooting_rocket_draw(struct task *task)
{
    struct task_work *work = task->work;
    Angle ang;

    njPushMatrix(NULL);
    njTranslate(NULL, work->pos.x, work->pos.y, work->pos.z);
    TURN_VIA(njRotateZ, work->ang.z, ang);
    TURN_VIA(njRotateX, work->ang.x, ang);
    TURN_VIA(njRotateY, work->ang.y, ang);
    njSetTexture_jp(&texlist_shooting0);
    late_DrawObject(&shooting_rocket_object);
    late_DrawObjectClipEx(1);
}

void shooting_rocket_destroy(struct task *task)
{
}

void shooting_rocket_take_touch(struct task *task)
{
    struct task_work *work = task->work;

    if (work->flags & COLLISION_TOUCHING) {
        work->mode = ROCKET_BLOW;
    }
}
