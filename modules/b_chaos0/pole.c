void ObjectDisplay(struct task *task)
{
    struct task_work *work = task->work;

    SetObjectTexture();
    njPushMatrix(NULL);
    njTranslateV(NULL, &work->pos);
    late_DrawObject(&chaos0_pole_object);
    late_DrawObjectClipEx(1);
}

void ObjectMain(struct task *task)
{
    if (!CheckRangeOut(task)) {
        /* @hack spelling: pole_draw called in each branch, which makes the set
         * editor's branch a tail call to it (BRA at 0x0c90534a). called once
         * ahead of the test, 20 of 26 words differ */
        if (OnEdit(task)) {
            ObjectDisplay(task);
        } else {
            ObjectDisplay(task);
            EntryColliList(task->work);
        }
    }
}

void pole_destroy(struct task *task)
{
}

void ObjectC0Pole(struct task *task)
{
    if (!CheckRangeOut(task)) {
        task->destructor = pole_destroy;
        CCL_Init(task, &pole_shape, COLLISION_OBJECT, 1, 1);
        task->step = ObjectMain;
        task->draw = ObjectDisplay;
    }
}
