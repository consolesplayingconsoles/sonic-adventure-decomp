void c0_gdcontrol(struct task *task)
{
    struct task_work *work = task->work;
    --work->timer;
    if (work->timer < 0) {
        ADXTaskInit();
        stream_request_and_save_music(work->mode);
        DestroyTask(task);
    }
}

void chaos0_start(struct task *task)
{
    struct task_work *work = task->work;

    GetStageNumber();
    FUN_8c0f0ac0();
    chaos0_create();
    chaos_effect_init();
    chaos0_rain_start();
    work->mode = CHAOS0_FIGHT;
    dsPlay_iloop(SE_HELD, -1, 8, 0);
}

void chaos0_end(struct task *task)
{
    ADX_Close();
}
