/* the wait asks for the music on its third step. that is the first with
 * more than MUSIC_DELAY steps before it */
#define MUSIC_DELAY 1

/* task->extra points to a Sint32, the steps the wait has run before this
 * one */
void eggmobile1_music_wait_step(struct task *task)
{
    Sint32 *waited = task->extra;

    if ((*waited)++ > MUSIC_DELAY) {
        BGM_Play(MUSIC_BOSSALL);
        FreeTask(task);
    }
}

void RdBossInit(void)
{
    struct task *task;
    Sint32 *waited;

    ADXTaskInit();
    if ((task = CreateElementalTask(0, 4, eggmobile1_music_wait_step)) !=
        NULL) {
        waited = CAlloc(1, sizeof(Sint32));
        task->extra = waited;
        *waited = 0;
    }
}

