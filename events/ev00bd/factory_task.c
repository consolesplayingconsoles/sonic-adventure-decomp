void CE101Factory_Draw(struct task *task)
{
    njPushMatrix(NULL);
    njTranslate(NULL, 0.0F, 500.0F, 0.0F);
    draw_e101factory();
    late_DrawObjectClipEx(1);
}

void ev00bd_factory_create(void)
{
    if (ev00bd_factory == NULL) {
        ev00bd_factory = CreateElementalTask(0, 5, CE101Factory_Draw);
    }
}

void ev00bd_factory_kill(void)
{
    if (ev00bd_factory != NULL) {
        FreeTask(ev00bd_factory);
        ev00bd_factory = NULL;
    }
}
